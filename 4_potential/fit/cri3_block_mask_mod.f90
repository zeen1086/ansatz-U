module cri3_block_mask_mod
  use parameter_mod
  implicit none

  private
  integer, parameter :: dp = kind(0d0)
  integer, parameter, public :: block_n_spinor = p_fit_nspinor
  integer, parameter :: n_block_features = 2 * block_n_spinor
  character(len=*), parameter, public :: block_mask_mode =                 &
    'seed_yellow34_c3_mirror_orbit_v1'

  public :: make_feature_block_mask
  public :: make_compact_feature_block_mask
  public :: apply_feature_block_mask
  public :: apply_com_block_mask
  public :: count_blocked_features
  public :: make_feature_active_fraction
  public :: masked_absmax_rhs

contains

  subroutine make_feature_block_mask(grid_nx, grid_ny, grid_nz, grid_size, mask)
    implicit none
    integer, intent(in) :: grid_nx, grid_ny, grid_nz, grid_size
    real(dp), intent(out) :: mask(grid_size,n_block_features)

    call make_orbit_closed_block_mask(grid_nx + 1, grid_ny + 1, grid_nz + 1,   &
      grid_size, max(grid_nx,1), max(grid_ny,1), max(grid_nz,1), mask)
  end subroutine make_feature_block_mask

  subroutine make_compact_feature_block_mask(nx_points, ny_points, nz_points,   &
      grid_size, mask)
    implicit none
    integer, intent(in) :: nx_points, ny_points, nz_points, grid_size
    real(dp), intent(out) :: mask(grid_size,n_block_features)

    call make_orbit_closed_block_mask(nx_points, ny_points, nz_points,         &
      grid_size, max(nx_points - 1,1), max(ny_points - 1,1),                  &
      max(nz_points - 1,1), mask)
  end subroutine make_compact_feature_block_mask

  subroutine make_orbit_closed_block_mask(nx_points, ny_points, nz_points,     &
      grid_size, denom_x, denom_y, denom_z, mask)
    implicit none
    integer, intent(in) :: nx_points, ny_points, nz_points, grid_size
    integer, intent(in) :: denom_x, denom_y, denom_z
    real(dp), intent(out) :: mask(grid_size,n_block_features)
    logical, allocatable :: blocked(:,:)
    integer :: ix, iy, iz, i

    if (grid_size /= nx_points * ny_points * nz_points) then
      stop 'block mask grid size mismatch'
    end if

    allocate(blocked(grid_size,n_block_features))
    blocked(:,:) = .false.

    do iz = 0, nz_points - 1
      do iy = 0, ny_points - 1
        do ix = 0, nx_points - 1
          i = index_from_grid(ix, iy, iz, nx_points, ny_points)
          call seed_block_channels_for_point(ix, iy, denom_x, denom_y,         &
            blocked(i,:))
        end do
      end do
    end do

    call close_seed_under_point_group(nx_points, ny_points, nz_points, denom_x,&
      denom_y, denom_z, blocked)

    mask(:,:) = 1d0
    where (blocked) mask = 0d0
    deallocate(blocked)
  end subroutine make_orbit_closed_block_mask

  subroutine seed_block_channels_for_point(ix, iy, denom_x, denom_y,            &
      blocked_row)
    implicit none
    integer, intent(in) :: ix, iy, denom_x, denom_y
    logical, intent(inout) :: blocked_row(n_block_features)

    ! Seed only the professor's yellow block: iy > ix blocks channels 3 and 4.
    ! The other blocked sectors are generated by C3/mirror closure below.
    if (inside_seed_yellow_region(ix, iy, denom_x, denom_y)) then
      call block_channel_pair(blocked_row, 3, 4)
    end if

  end subroutine seed_block_channels_for_point

  logical function inside_seed_yellow_region(ix, iy, denom_x, denom_y)
    implicit none
    integer, intent(in) :: ix, iy, denom_x, denom_y
    real(dp) :: x_frac, y_frac

    x_frac = real(ix,dp) / real(denom_x,dp)
    y_frac = real(iy,dp) / real(denom_y,dp)
    inside_seed_yellow_region = y_frac > x_frac
  end function inside_seed_yellow_region

  subroutine close_seed_under_point_group(nx_points, ny_points, nz_points,      &
      denom_x, denom_y, denom_z, blocked)
    implicit none
    integer, intent(in) :: nx_points, ny_points, nz_points
    integer, intent(in) :: denom_x, denom_y, denom_z
    logical, intent(inout) :: blocked(:,:)
    integer, parameter :: max_closure_iter = 64
    integer :: iter
    logical :: changed, any_changed
    real(dp) :: origin(3), transform(3,3)

    do iter = 1, max_closure_iter
      any_changed = .false.

      origin = (/real(denom_x,dp)/3d0, 2d0*real(denom_y,dp)/3d0,              &
        real(denom_z,dp)/2d0/)
      call c3_plus_transform(transform)
      call close_under_operation(nx_points, ny_points, nz_points, denom_x,     &
        denom_y, denom_z, origin, transform, blocked, changed)
      any_changed = any_changed .or. changed
      call c3_minus_transform(transform)
      call close_under_operation(nx_points, ny_points, nz_points, denom_x,     &
        denom_y, denom_z, origin, transform, blocked, changed)
      any_changed = any_changed .or. changed

      origin = (/2d0*real(denom_x,dp)/3d0, real(denom_y,dp)/3d0,              &
        real(denom_z,dp)/2d0/)
      call c3_plus_transform(transform)
      call close_under_operation(nx_points, ny_points, nz_points, denom_x,     &
        denom_y, denom_z, origin, transform, blocked, changed)
      any_changed = any_changed .or. changed
      call c3_minus_transform(transform)
      call close_under_operation(nx_points, ny_points, nz_points, denom_x,     &
        denom_y, denom_z, origin, transform, blocked, changed)
      any_changed = any_changed .or. changed

      origin = (/0d0, 0d0, 0d0/)
      call mirror_transform(transform)
      call close_under_operation(nx_points, ny_points, nz_points, denom_x,     &
        denom_y, denom_z, origin, transform, blocked, changed)
      any_changed = any_changed .or. changed

      if (.not. any_changed) return
    end do

    stop 'block mask point-group closure did not converge'
  end subroutine close_seed_under_point_group

  subroutine close_under_operation(nx_points, ny_points, nz_points, denom_x,    &
      denom_y, denom_z, origin, transform, blocked, changed)
    implicit none
    integer, intent(in) :: nx_points, ny_points, nz_points
    integer, intent(in) :: denom_x, denom_y, denom_z
    real(dp), intent(in) :: origin(3), transform(3,3)
    logical, intent(inout) :: blocked(:,:)
    logical, intent(out) :: changed
    integer :: ix, iy, iz, i, j, feature, channel, mapped_channel
    integer :: mapped_feature, ix_map, iy_map, iz_map
    integer :: pt_map(block_n_spinor)
    real(dp) :: channel_pos(block_n_spinor,3)
    real(dp) :: mapped_grid(3)
    logical, allocatable :: old_blocked(:,:)

    call build_channel_positions(denom_x, denom_y, denom_z, channel_pos)
    call build_channel_map(origin, transform, channel_pos, pt_map)

    allocate(old_blocked(size(blocked,1),size(blocked,2)))
    old_blocked = blocked
    changed = .false.

    do iz = 0, nz_points - 1
      do iy = 0, ny_points - 1
        do ix = 0, nx_points - 1
          i = index_from_grid(ix, iy, iz, nx_points, ny_points)
          mapped_grid = origin + matmul(transpose(transform),                  &
            (/real(ix,dp), real(iy,dp), real(iz,dp)/) - origin)
          ix_map = nint(mapped_grid(1))
          iy_map = nint(mapped_grid(2))
          iz_map = nint(mapped_grid(3))

          if (abs(mapped_grid(1) - real(ix_map,dp)) > 1d-8) cycle
          if (abs(mapped_grid(2) - real(iy_map,dp)) > 1d-8) cycle
          if (abs(mapped_grid(3) - real(iz_map,dp)) > 1d-8) cycle
          if (ix_map < 0 .or. ix_map >= nx_points) cycle
          if (iy_map < 0 .or. iy_map >= ny_points) cycle
          if (iz_map < 0 .or. iz_map >= nz_points) cycle

          j = index_from_grid(ix_map, iy_map, iz_map, nx_points, ny_points)
          do feature = 1, n_block_features
            if (.not. old_blocked(i,feature)) cycle
            if (feature <= block_n_spinor) then
              channel = feature
              mapped_channel = pt_map(channel)
              if (mapped_channel > block_n_spinor) cycle
              mapped_feature = mapped_channel
            else
              channel = feature - block_n_spinor
              mapped_channel = pt_map(channel)
              if (mapped_channel > block_n_spinor) cycle
              mapped_feature = block_n_spinor + mapped_channel
            end if
            if (.not. blocked(j,mapped_feature)) then
              blocked(j,mapped_feature) = .true.
              changed = .true.
            end if
          end do
        end do
      end do
    end do

    deallocate(old_blocked)
  end subroutine close_under_operation

  subroutine build_channel_positions(denom_x, denom_y, denom_z, positions)
    implicit none
    integer, intent(in) :: denom_x, denom_y, denom_z
    real(dp), intent(out) :: positions(block_n_spinor,3)

    positions(1,:) = (/2d0/3d0, 1d0/3d0, 0.5d0/)
    positions(2,:) = (/1d0/3d0, 2d0/3d0, 0.5d0/)
    positions(3,:) = (/1d0/3d0, -1d0/3d0, 0.5d0/)
    positions(4,:) = (/4d0/3d0, 2d0/3d0, 0.5d0/)
    positions(5,:) = (/-1d0/3d0, 1d0/3d0, 0.5d0/)
    positions(6,:) = (/2d0/3d0, 4d0/3d0, 0.5d0/)

    positions(:,1) = positions(:,1) * real(denom_x,dp)
    positions(:,2) = positions(:,2) * real(denom_y,dp)
    positions(:,3) = positions(:,3) * real(denom_z,dp)
  end subroutine build_channel_positions

  subroutine build_channel_map(origin, transform, positions, pt_map)
    implicit none
    real(dp), intent(in) :: origin(3), transform(3,3)
    real(dp), intent(in) :: positions(block_n_spinor,3)
    integer, intent(out) :: pt_map(block_n_spinor)
    integer :: channel, mapped_channel
    real(dp) :: mapped_pos(3)

    pt_map = block_n_spinor + 1
    do channel = 1, block_n_spinor
      mapped_pos = origin + matmul(transpose(transform),                       &
        positions(channel,:) - origin)
      do mapped_channel = 1, block_n_spinor
        if (sum((mapped_pos - positions(mapped_channel,:))**2) < 1d-3) then
          pt_map(channel) = mapped_channel
        end if
      end do
    end do
  end subroutine build_channel_map

  subroutine c3_plus_transform(transform)
    implicit none
    real(dp), intent(out) :: transform(3,3)

    transform(1,:) = (/0d0, 1d0, 0d0/)
    transform(2,:) = (/-1d0, -1d0, 0d0/)
    transform(3,:) = (/0d0, 0d0, 1d0/)
  end subroutine c3_plus_transform

  subroutine c3_minus_transform(transform)
    implicit none
    real(dp), intent(out) :: transform(3,3)

    transform(1,:) = (/-1d0, -1d0, 0d0/)
    transform(2,:) = (/1d0, 0d0, 0d0/)
    transform(3,:) = (/0d0, 0d0, 1d0/)
  end subroutine c3_minus_transform

  subroutine mirror_transform(transform)
    implicit none
    real(dp), intent(out) :: transform(3,3)

    transform(1,:) = (/0d0, 1d0, 0d0/)
    transform(2,:) = (/1d0, 0d0, 0d0/)
    transform(3,:) = (/0d0, 0d0, 1d0/)
  end subroutine mirror_transform

  integer function index_from_grid(ix, iy, iz, nx_points, ny_points)
    implicit none
    integer, intent(in) :: ix, iy, iz, nx_points, ny_points

    index_from_grid = 1 + ix + nx_points * iy + nx_points * ny_points * iz
  end function index_from_grid

  subroutine block_channel_pair(blocked_row, channel_a, channel_b)
    implicit none
    logical, intent(inout) :: blocked_row(n_block_features)
    integer, intent(in) :: channel_a, channel_b

    blocked_row(channel_a) = .true.
    blocked_row(channel_b) = .true.
    blocked_row(block_n_spinor+channel_a) = .true.
    blocked_row(block_n_spinor+channel_b) = .true.
  end subroutine block_channel_pair

  subroutine apply_feature_block_mask(coef, mask)
    implicit none
    real(dp), intent(inout) :: coef(:,:)
    real(dp), intent(in) :: mask(:,:)

    if (size(coef,1) /= size(mask,1)) stop 'block mask grid mismatch'
    if (size(coef,2) /= size(mask,2)) stop 'block mask feature mismatch'
    coef(:,:) = coef(:,:) * mask(:,:)
  end subroutine apply_feature_block_mask

  subroutine apply_com_block_mask(linear_part, mod_part, mask)
    implicit none
    real(dp), intent(inout) :: linear_part(:,:), mod_part(:,:)
    real(dp), intent(in) :: mask(:,:)
    integer :: channel

    if (size(linear_part,1) /= size(mask,1)) stop 'block mask grid mismatch'
    if (size(mod_part,1) /= size(mask,1)) stop 'block mask grid mismatch'
    if (size(linear_part,2) /= block_n_spinor) stop 'linear channel mismatch'
    if (size(mod_part,2) /= block_n_spinor) stop 'mod channel mismatch'
    if (size(mask,2) /= n_block_features) stop 'block mask feature mismatch'

    do channel = 1, block_n_spinor
      linear_part(:,channel) = linear_part(:,channel) * mask(:,channel)
      mod_part(:,channel) = mod_part(:,channel) * mask(:,block_n_spinor+channel)
    end do
  end subroutine apply_com_block_mask

  integer function count_blocked_features(mask)
    implicit none
    real(dp), intent(in) :: mask(:,:)

    count_blocked_features = count(mask < 0.5d0)
  end function count_blocked_features

  subroutine make_feature_active_fraction(mask, active_fraction)
    implicit none
    real(dp), intent(in) :: mask(:,:)
    real(dp), intent(out) :: active_fraction(:)
    integer :: feature

    if (size(active_fraction) /= size(mask,2)) stop 'active fraction mismatch'

    do feature = 1, size(mask,2)
      active_fraction(feature) = sum(mask(:,feature)) / real(size(mask,1),dp)
    end do
  end subroutine make_feature_active_fraction

  real(dp) function masked_absmax_rhs(rhs, mask)
    implicit none
    real(dp), intent(in) :: rhs(:,:), mask(:,:)
    integer :: ip, jf

    if (size(rhs,1) /= size(mask,2)) stop 'rhs/mask feature mismatch'
    if (size(rhs,2) /= size(mask,1)) stop 'rhs/mask grid mismatch'

    masked_absmax_rhs = 0d0
    do ip = 1, size(mask,1)
      do jf = 1, size(mask,2)
        if (mask(ip,jf) > 0.5d0) then
          masked_absmax_rhs = max(masked_absmax_rhs, abs(rhs(jf,ip)))
        end if
      end do
    end do
  end function masked_absmax_rhs

end module cri3_block_mask_mod
